def mask_product_properly(image_bytes):
    # 1. Remove background (returns RGBA)
    output_bytes = remove(image_bytes)
    img = Image.open(io.BytesIO(output_bytes)).convert("RGBA")

    # 2. Create a white background
    # This ensures the product isn't floating in "blackness"
    white_bg = Image.new("RGBA", img.size, (255, 255, 255, 255))
    composite = Image.alpha_composite(white_bg, img).convert("RGB")

    return composite

