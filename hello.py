def perform_contrastive_sampling(reviews, meta, samples_per_class=50):
    # 1. Clean data: Ensure images exist and handle nesting
    reviews = reviews[reviews['images'].apply(lambda x: len(x) > 0 if isinstance(x, list) else False)].copy()

    # Extract URLs into a clean column
    def get_first_img(img_list):
        first = img_list[0]
        return first['large_image_url'] if isinstance(first, dict) else first

    reviews['user_img_url'] = reviews['images'].apply(get_first_img)

    # 2. Define Contrastive Patterns
    misleading_keywords = ['different', 'fake', 'cheap', 'not as pictured', 'misleading', 'wrong color', 'poor quality']
    accurate_keywords = ['exactly', 'pictured', 'accurate', 'as shown', 'perfect match', 'same as photo']

    # 3. Create "Misleading" Bucket (Labels: 1)
    misleading_mask = (reviews['rating'] < 3.0) & (reviews['text'].str.contains('|'.join(misleading_keywords), case=False, na=False))
    df_misleading = reviews[misleading_mask].head(samples_per_class).copy()
    df_misleading['label'] = 1  # 1 = Misleading / Discrepancy exists

    # 4. Create "Accurate" Bucket (Labels: 0)
    accurate_mask = (reviews['rating'] > 4.0) & (reviews['text'].str.contains('|'.join(accurate_keywords), case=False, na=False))
    df_accurate = reviews[accurate_mask].head(samples_per_class).copy()
    df_accurate['label'] = 0  # 0 = Accurate / No discrepancy

    # 5. Merge with Metadata to get Catalog Images
    contrastive_df = pd.concat([df_misleading, df_accurate])

    # Join on parent_asin
    final_df = contrastive_df.merge(meta[['parent_asin', 'images']], on='parent_asin', how='inner', suffixes=('_user', '_meta'))

    # Clean up catalog image URL
    def get_meta_img(img_list):
        if not isinstance(img_list, list) or len(img_list) == 0: return None
        first = img_list[0]
        return first['large'] if isinstance(first, dict) else first

    final_df['catalog_img_url'] = final_df['images_meta'].apply(get_meta_img)

    # Final cleanup: Keep only what we need
    return final_df[['parent_asin', 'rating', 'text', 'user_img_url', 'catalog_img_url', 'label']].dropna()

